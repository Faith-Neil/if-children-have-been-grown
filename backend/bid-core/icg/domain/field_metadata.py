# 别名映射，提高容错性
CATEGORY_ALIASES: dict[str, str] = {
    "bid_project": "project",
    "projects": "project",
    "tender_requirement": "tender",
    "requirement": "tender",
    "tenders": "tender",
    "library": "kb_record",
    "kb": "kb_record",
    "records": "kb_record",
    "project_sla": "sla",
    "sla_value": "sla",
    "sla_template": "sla",
}


class FieldMetadataService:
    def __init__(self, service: DemoService):
        self.service = service

    def resolve_category(self, category: str) -> str:
        cat_key = category.strip().lower()
        if cat_key in METADATA_DEFINITIONS:
            return cat_key
        if cat_key in CATEGORY_ALIASES:
            return CATEGORY_ALIASES[cat_key]
        raise DomainError(404, "NOT_FOUND", f"未找到该分类的字段元数据：{category}。")

    def get_fields(self, category: str, principal: Principal) -> dict[str, Any]:
        canonical_category = self.resolve_category(category)
        definition = METADATA_DEFINITIONS[canonical_category]
        fields_data = [FieldMetadataItem(**item) for item in definition["fields"]]
        return {
            "category": canonical_category,
            "category_name": definition["category_name"],
            "total": len(fields_data),
            "fields": fields_data,
            "items": fields_data,
        }


def include_field_metadata_routes(application, service: DemoService, current_user) -> None:
    metadata_service = FieldMetadataService(service)
    application.state.field_metadata_service = metadata_service

    router = APIRouter(prefix="/api/v1", responses=v1_error_responses(401, 403, 404, 500))

    @router.get(
        "/metadata/fields/{category}",
        response_model=FieldMetadataListResponse,
        operation_id="getFieldMetadata",
        summary="获取指定分类的字段元数据",
        description="按数据字典与表单/表格规范返回分类字段的元数据定义，包含字段键、标签、类型、必填、可编辑性、宽度、对齐、渲染类型等属性。",
    )
    def get_field_metadata(category: str, user: Principal = Depends(current_user)):
        return metadata_service.get_fields(category, user)

    application.include_router(router)
