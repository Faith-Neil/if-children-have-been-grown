class FieldOption(BaseModel):
    value: str = Field(description="选项值/代码")
    label: str = Field(description="选项显示名称")
    badge_status: str | None = Field(default=None, description="状态标识类型或颜色提示")


class FieldMetadataItem(BaseModel):
    field_key: str = Field(description="字段键（snake_case）")
    label: str = Field(description="字段中文显示标签")
    data_type: str = Field(description="逻辑数据类型：string, integer, number, boolean, date, datetime, array, object")
    required: bool = Field(default=False, description="是否必填")
    editable: bool = Field(default=True, description="是否允许人工编辑")
    default_width: int | None = Field(default=None, description="表格默认列宽（像素），空表示自适应")
    align: str = Field(default="left", description="表格对齐方式：left, center, right")
    render_type: str = Field(default="text", description="渲染组件类型：text, tag, badge, date, datetime, number, cite, masked, link, select")
    filterable: bool = Field(default=False, description="是否支持表格过滤筛选")
    sortable: bool = Field(default=False, description="是否支持表格列排序")
    is_starred: bool = Field(default=False, description="是否★关键字段（修改后需重新确认）")
    is_sensitive: bool = Field(default=False, description="是否敏感字段（需掩码展示）")
    system_key: str | None = Field(default=None, description="系统字段键（用于表单两行标签展示）")
    placeholder: str | None = Field(default=None, description="输入占位说明文案")
    description: str | None = Field(default=None, description="字段业务释义与校验说明")
    options: list[FieldOption] | None = Field(default=None, description="枚举或代码表可选列表")


class FieldMetadataListResponse(BaseModel):
    category: str = Field(description="规范分类标识")
    category_name: str = Field(description="分类中文名称")
    total: int = Field(description="字段总数")
    fields: list[FieldMetadataItem] = Field(description="字段元数据列表")
    items: list[FieldMetadataItem] | None = Field(default=None, description="字段列表别名，兼容 items 结构")


